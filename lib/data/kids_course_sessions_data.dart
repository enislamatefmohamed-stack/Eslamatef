class KidsSessionItem {
  final int number;
  final String title;
  final int levelNumber;
  final String levelName;
  final String description;
  final int slidesCount;
  final bool isReady;
  final String? webUrl;
  final String? quizUrl;
  final List<String> topics;

  const KidsSessionItem({
    required this.number,
    required this.title,
    required this.levelNumber,
    required this.levelName,
    required this.description,
    this.slidesCount = 25,
    this.isReady = false,
    this.webUrl,
    this.quizUrl,
    this.topics = const [],
  });

  String get formattedNumber => number < 10 ? '0$number' : '$number';

  void launchSession() {
    final customCode = SiteDataService.instance.getKidsSessionCustomCode(number);
    if (customCode != null && customCode.trim().isNotEmpty) {
      openRecordingPresentation(customCode, title: title);
      return;
    }
    if (webUrl != null && webUrl!.isNotEmpty) {
      html.window.open(webUrl!, '_blank');
    }
  }

  void launchQuiz() {
    if (quizUrl != null && quizUrl!.isNotEmpty) {
      html.window.open(quizUrl!, '_blank');
    }
  }
}

